function rowIntervals(polygon,y) {
  const xs=[];
  for(let i=0,j=polygon.length-1;i<polygon.length;j=i++){
    const a=polygon[j],b=polygon[i];
    if((a[1]>y)!==(b[1]>y))xs.push(a[0]+(y-a[1])*(b[0]-a[0])/(b[1]-a[1]));
  }
  xs.sort((a,b)=>a-b);
  const intervals=[];for(let i=0;i+1<xs.length;i+=2)intervals.push([xs[i],xs[i+1]]);
  return intervals;
}
function rowSpan(polygon,y) {const spans=rowIntervals(polygon,y);return spans.length?[spans[0][0],spans[spans.length-1][1]]:null;}

const tyreRowCache=new WeakMap();
function tyreRows(image,polygon) {
  let cache=tyreRowCache.get(image);if(!cache){cache=new WeakMap();tyreRowCache.set(image,cache);}
  if(cache.has(polygon))return cache.get(polygon);
  const c=document.createElement('canvas');c.width=image.width;c.height=image.height;
  const cx=c.getContext('2d');cx.drawImage(image,0,0);
  const pixels=cx.getImageData(0,0,c.width,c.height).data;
  const rows=new Map();
  const y0=Math.max(0,Math.floor(Math.min(...polygon.map(p=>p[1]))*image.height));
  const y1=Math.min(image.height,Math.ceil(Math.max(...polygon.map(p=>p[1]))*image.height));
  for(let y=y0;y<y1;y++){
    let best=null;
    for(const span of rowIntervals(polygon,(y+.5)/image.height)){
      const left=Math.max(0,Math.ceil(span[0]*image.width-.5)),right=Math.min(image.width-1,Math.floor(span[1]*image.width-.5));
      let start=-1;
      for(let x=left;x<=right+1;x++){
        const opaque=x<=right&&pixels[(y*image.width+x)*4+3]>=96;
        if(opaque&&start<0)start=x;
        if(!opaque&&start>=0){if(!best||x-start>best[1]-best[0])best=[start,x];start=-1;}
      }
    }
    if(best)rows.set(y,best);
  }
  // Keep compact spans, not a second full RGBA copy of every source image.
  c.width=c.height=1;cache.set(polygon,rows);return rows;
}

export function drawWheelPatches(g,image,width,height,art) {
  const original=g.getImageData(0,0,g.canvas.width,g.canvas.height);
  const coverage=document.createElement('canvas');coverage.width=g.canvas.width;coverage.height=g.canvas.height;
  const mask=coverage.getContext('2d');mask.setTransform(g.getTransform());mask.fillStyle='white';
  for(const patch of art.patches||[]){
    mask.beginPath();patch.polygon.forEach(([u,v],i)=>i?mask.lineTo(u*width,v*height):mask.moveTo(u*width,v*height));mask.closePath();mask.fill();
    g.save();g.beginPath();
    patch.polygon.forEach(([u,v],i)=>i?g.lineTo(u*width,v*height):g.moveTo(u*width,v*height));
    g.closePath();g.clip();
    // Opaque tyre paint composites over the old silhouette, retaining its
    // antialiased boundary coverage. Clearing and painting through the same
    // clip twice would punch one-pixel holes at some scaled polygon edges.
    // A geometry replacement must instead erase the obsolete silhouette.
    if(patch.silhouetteReplacement)g.clearRect(0,0,width,height);
    const [sx,sy,sw,sh]=patch.source||art.crop||[0,0,1,1];
    const [dx,dy,dw,dh]=patch.target||[0,0,1,1];
    if(patch.sourcePolygon){
      // Cache-time contour registration retains the full painted shoulder
      // and tread instead of stretching a narrow, flat centre strip.
      const transform=g.getTransform(),scale=Math.max(1,Math.hypot(transform.c,transform.d));
      const rows=tyreRows(image,patch.sourcePolygon),validRows=[...rows.keys()];
      for(let row=Math.floor(dy*height*scale);row<Math.ceil((dy+dh)*height*scale);row++){
        const v=(row+.5)/(height*scale),target=rowSpan(patch.polygon,v);
        const sv=Math.max(sy+.5/image.height,Math.min(sy+sh-.5/image.height,sy+(v-dy)/dh*sh));
        let sourceY=Math.floor(sv*image.height),source=rows.get(sourceY);
        if(!source&&validRows.length){sourceY=validRows.reduce((a,b)=>Math.abs(b-sourceY)<Math.abs(a-sourceY)?b:a);source=rows.get(sourceY);}
        if(!target||!source||target[1]<=target[0]||source[1]<=source[0])continue;
        // Integer source rows and opaque runs avoid stretching transparent
        // antialias fringes into holes in an otherwise solid rear tyre.
        g.drawImage(image,source[0],sourceY,source[1]-source[0],1,target[0]*width,row/scale,(target[1]-target[0])*width,1/scale);
      }
    }else g.drawImage(image,sx*image.width,sy*image.height,sw*image.width,sh*image.height,dx*width,dy*height,dw*width,dh*height);
    g.restore();
  }
  // Canvas clipped clear/draw can change hidden RGB on a transparent edge.
  // Keep every pixel outside the traced tyre coverage exactly original.
  const result=g.getImageData(0,0,g.canvas.width,g.canvas.height),covered=mask.getImageData(0,0,coverage.width,coverage.height).data;
  for(let i=0;i<covered.length;i+=4){
    if(!covered[i+3])for(let c=0;c<4;c++)result.data[i+c]=original.data[i+c];
    // Normalize before putImageData to avoid another premultiplied-alpha
    // round trip changing edge RGB outside the wheel mask.
    result.data[i+3]=result.data[i+3]<96?0:255;
  }
  g.putImageData(result,0,0);
}
